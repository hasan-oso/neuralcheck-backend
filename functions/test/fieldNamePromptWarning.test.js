'use strict';

// fieldNamePromptWarning.test.js — أمر مستخدم 2026-09-23 +03 (بعد A125)،
// البند ٣ (تنبيه منفصل عن البند ٥ — ذاك يخصّ قيم state، هذا يخصّ أسماء
// حقول JSON نفسها): "والنموذج يُنبَّه في البرومبت ألّا ينقل أسماء الحقول
// بالإنجليزية — يُسمّي المعنى لا المفتاح... بلا أي رقم عتبة. وتبقى أسماء
// البوّابات مسموحة، فهي فئة gate_name."
//
// القاعدة 34 (فُحصت قبل الكتابة): قارئا systemPromptV7.js الحقيقيان في
// هذا المستودع — grep "require(.*systemPromptV7" src test — هما
// src/analysis/callAI.js (إنتاج، لا يفحص محتوى النصّ) وtest/systemPromptV7.test.js
// (يفحص القرار ٩ بنمط THRESHOLD_UNIT_PATTERN عدد+وحدة، لا يتأثّر بمعرّف
// نصّي كـ"vsyncLockFraction60" — الرقم فيه جزء اسم لا عتبة قرار، تماماً
// كـ"SEC-04"/"C-04" الموجودتين أصلاً في النصّ). لا ثابت حجم على البرومبت
// في أي مكان (grep "systemPrompt.length\|SYSTEM_PROMPT_V7.length" src
// test: صفر نتيجة).
//
// Run: node functions/test/fieldNamePromptWarning.test.js

const assert = require('assert');
const {getSystemPromptV7} = require('../src/prompts/systemPromptV7');

let n = 0;
const ok = (c, m) => { assert.ok(c, m); n++; };

// نفس نمط القرار ٩ الثابت في systemPromptV7.test.js (القاعدة 24 — لا نسخة
// منطقية جديدة، إعادة استعمال حرفي لنفس التعريف).
const THRESHOLD_UNIT_PATTERN = /[0-9]+(\.[0-9]+)?\s*-?\s*(mV|mAh|GHz|MB\/s|%|°C|mΩ|هرتز|جيجاهرتز)/g;

for (const lang of ['ar', 'tr']) {
  const prompt = getSystemPromptV7(lang);

  // ═══════════════════════════════════════════════════════════════════
  // ١ — فقرة التنبيه حاضرة، وتذكر أمثلة أسماء حقول JSON حقيقية.
  // ═══════════════════════════════════════════════════════════════════
  const idx = prompt.indexOf('أسماء حقول JSON');
  ok(idx >= 0, `[١] فقرة تنبيه أسماء الحقول حاضرة في البرومبت (${lang})`);
  const block = prompt.slice(idx, idx + 500);
  ok(block.includes('vsyncLockFraction60') || block.includes('categoryStates'),
      `[١] الفقرة تذكر مثالاً حقيقياً لاسم حقل JSON (${lang})`);
  ok(/سمِّ معناه بالعربية|معناها بالعربية/.test(block),
      `[١] الفقرة تطلب كتابة المعنى بالعربية لا نقل الاسم حرفياً (${lang})`);

  // ═══════════════════════════════════════════════════════════════════
  // ٢ — S5 (أمر مستخدم 2026-10-01 +03، القاعدة 23 — استُبدل لا أُضيف):
  // كان هذا يُثبت أن أسماء البوّابات (gate_name) مستثناة صراحة من منع نقل
  // أسماء الحقول حرفياً. عُكس ذلك: البوّابات لم تَعُد مستثناة — ممنوعة
  // كلّياً من أي نثر بشري (راجع systemPromptV7.test.js لاختبار القسم
  // الجديد "ما لا يصل المشتري إطلاقاً" مباشرة). هنا يكفي إثبات أن فقرة
  // أسماء حقول JSON نفسها لم تَعُد تحمل عبارة الاستثناء القديمة.
  // ═══════════════════════════════════════════════════════════════════
  ok(!block.includes('لا يشمل أسماء البوّابات المسمّاة'),
      `[٢][S5] فقرة أسماء حقول JSON لم تَعُد تستثني أسماء البوّابات — الاستثناء القديم أُزيل (${lang})`);

  // ═══════════════════════════════════════════════════════════════════
  // ٣ — بلا أي رقم عتبة (القرار ٩) — نفس نمط الفحص المُعتمَد في
  // systemPromptV7.test.js، مُطبَّق على فقرة هذا التنبيه تحديداً.
  // ═══════════════════════════════════════════════════════════════════
  const unitMatches = block.match(THRESHOLD_UNIT_PATTERN);
  ok(!unitMatches, `[٣] صفر رقم-وحدة (عتبة قرار) داخل فقرة تنبيه أسماء الحقول (${lang}) — ${JSON.stringify(unitMatches)}`);
  const rangeMatches = block.match(/0\.\d+\s*[-–]\s*0\.\d+/g);
  ok(!rangeMatches, `[٣] صفر نطاق عشري ثابت داخل الفقرة (${lang})`);
}
console.log('تحقّق ١-٣: فقرة تنبيه أسماء الحقول حاضرة في اللغتين، لم تَعُد تستثني gate_name (S5)، وبلا أي رقم عتبة');

console.log(`\nfieldNamePromptWarning.test.js: ${n}/${n} assertions passed`);
