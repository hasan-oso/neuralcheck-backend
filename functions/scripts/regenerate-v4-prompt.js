// Regenerate functions/src/prompts/systemPromptV4.js from V4_PROMPT_SOURCE.md.
//
// Usage: node functions/scripts/regenerate-v4-prompt.js
//
// Whenever the lab ships a new prompt version, replace V4_PROMPT_SOURCE.md
// with the new content and re-run this script. It handles template-literal
// escaping (backticks, ${} sequences, backslashes) so you don't have to.

const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "..", "src", "prompts", "V4_PROMPT_SOURCE.md");
const DST = path.join(__dirname, "..", "src", "prompts", "systemPromptV4.js");

function escapeForTemplateLiteral(s) {
  // Order matters: escape backslash first, then backtick and ${.
  return s
      .replace(/\\/g, "\\\\")
      .replace(/`/g, "\\`")
      .replace(/\$\{/g, "\\${");
}

const md = fs.readFileSync(SRC, "utf8");
const escaped = escapeForTemplateLiteral(md);

const output = `// V4 SYSTEM PROMPT — Layer 1+2+3 architecture
//
// Source: copied from neuralcheck-lab/deepseek_integration/enriched_prompt.md
// (v63). DO NOT EDIT THIS FILE DIRECTLY. Edit V4_PROMPT_SOURCE.md and
// regenerate this file via:
//   node functions/scripts/regenerate-v4-prompt.js
//
// To activate V4: see runAnalysisInternal.js where SYSTEM_PROMPT is selected.

const SYSTEM_PROMPT_V4 = \`${escaped}\`;

module.exports = {SYSTEM_PROMPT_V4};
`;

fs.writeFileSync(DST, output);
console.log(`Wrote ${DST}`);
console.log(`  source bytes: ${md.length}`);
console.log(`  escaped bytes: ${escaped.length}`);
console.log(`  output bytes: ${output.length}`);
